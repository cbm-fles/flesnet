#include "Parameters.hpp"
#include "CommonOptions.hpp"
#include "log.hpp"
#include "log_program_options.hpp"
#include <boost/program_options.hpp>
#include <boost/program_options/value_semantic.hpp>
#include <iostream>
#include <ostream>
#include <sstream>

namespace po = boost::program_options;
using namespace std;
void Parameters::parse_options(int argc, char* argv[]) {
  po::options_description general("General options");
  auto general_add = general.add_options();
  fles::add_general_options(general);
  logging::add_program_options(general);
  general_add("max-threads,j",
              po::value<uint64_t>(&max_threads)
                  ->default_value(1)
                  ->value_name("<n>"),
              "How many threads to use for validation. Set to 0 to use all available physical cores.");
  general_add("skip-metadata",
              po::value<bool>(&skip_metadata)
                  ->implicit_value(true),
              "Will skip timeslice archive metadata verification.");
  general_add("ms-start-idx",
              po::value<uint64_t>(&ms_start_idx)
                  ->default_value(0)
                  ->value_name("<n>"),
              "Start verification process at microslice index n.");
  general_add("tsa-forwarding",
              po::bool_switch(&check_tsa_forwarding));

  po::options_description archives("Input/Output archives");
  auto archives_add = archives.add_options();
  archives_add("input-archives,I", po::value<vector<string>>(&input_archives)->multitoken()->value_name("<space-separated-archive-files>"),
               "Paths to input archives (.msa or .tsa based on use case).");
  archives_add("output-archives,O", po::value<vector<string>>(&output_archives)->multitoken()->value_name("<space-separated-tsa-files>"),
               "Paths to output archives (.tsa).");
  archives_add("verify-tsa,t", po::value<vector<string>>(&tsa_archives)
                                   ->multitoken()
                                   ->value_name("<space-separated-tsa-files>"));
  po::options_description ts_parameters("Timeslice parameters");
  auto ts_parameters_add = ts_parameters.add_options();
  ts_parameters_add("timeslice-cnt", po::value<uint64_t>(&timeslice_cnt)->default_value(0)->value_name("<n>"),
                    "Summed up number of expected timeslices in the timeslice archives. Don't use this option for a more relaxed verification process.");
  ts_parameters_add("timeslice-size", po::value<uint64_t>(&timeslice_size)->value_name("<n>"),
                    "Expected timeslice size.");
  ts_parameters_add("overlap", po::value<uint64_t>(&overlap)->default_value(overlap)->value_name("<n>"),
                    "Timeslice overlap size.");

  stringstream desc_sstr;
  desc_sstr << endl
            << "Usage:" << endl
            << "\tarchive_validator [options] -I input1.msa [ input2.msa ... ] -O output1.tsa [ output2.tsa ... ]" << endl
            << endl
            << "This program checks if the output data was generated by the given input data." << endl
            << "Output data is defined by timeslice archive files (*.tsa)." << endl
            << "Input data is defined by microslice archive files (*.msa)" << endl
            << "Use the 'timeslice parameters' to define the expected structure of the timeslices in the provided .tsa files"
            << endl
            << endl
            << "Command line options";
  po::options_description desc(desc_sstr.str());
  desc
      .add(general)
      .add(archives)
      .add(ts_parameters);

  po::variables_map vm;
  po::store(po::parse_command_line(argc, argv, desc), vm);
  po::notify(vm);

  fles::handle_general_options(vm, "archive_validator", desc);

  logging::setup(fles::log_options(vm));

  bool analyze_parameter_set = true;
  // if (vm.count("timeslice-cnt") == 0) {
  //   L_(fatal) << "'timeslice-cnt' option not set";
  //   analyze_parameter_set = false;
  // }

  // if (vm.count("timeslice-size") == 0) {
  //   L_(fatal) << "'timeslice-size' option not set";
  //   analyze_parameter_set = false;
  // }

  // if (vm.count("input-archives") == 0) {
  //   L_(fatal) << "'input-archives' option not set";
  //   analyze_parameter_set = false;
  // }

  // if (vm.count("output-archives") == 0) {
  //   L_(fatal) << "'output-archives' option not set";
  //   analyze_parameter_set = false;
  // }

  if (!analyze_parameter_set) {
    throw ParametersException("Not all necessary parameters for archive analyzing are set.");
  }
}
